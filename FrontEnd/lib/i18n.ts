export function getCropDisplayName(crop: string, lang: Language): string {
  if (!crop) return "";
  const key = Object.keys(RWANDA_CROPS_I18N).find(
    (k) => k.toLowerCase() === crop.trim().toLowerCase()
  );
  if (key) {
    return RWANDA_CROPS_I18N[key][lang] || crop;
  }
  return crop;
}
